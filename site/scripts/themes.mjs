// Theme explorations: one source of truth for the 10 colour themes.
//   node scripts/themes.mjs          -> writes src/styles/themes.css and prints a WCAG contrast table
//   node scripts/themes.mjs --check  -> same, exits 1 if any pair fails AA
import { readFileSync, writeFileSync } from 'node:fs';

// Each theme: accent ("mint" token), its hover shade, a second accent, page bg, raised surface,
// body text, muted text, error text, text on accent fills, and particle settings.
const THEMES = JSON.parse(readFileSync(new URL('../src/config/themes.json', import.meta.url), 'utf8'));

const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const lum = (h) => {
  const [r, g, b] = hex(h).map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

// [label, fg key, bg key, minimum]
const PAIRS = [
  ['Body text / page', 'text', 'bg', 4.5],
  ['Body text / panel', 'text', 'surface', 4.5],
  ['Soft text / page', 'textSoft', 'bg', 4.5],
  ['Muted text / page', 'muted', 'bg', 4.5],
  ['Muted text / panel', 'muted', 'surface', 4.5],
  ['Accent text / page', 'mint', 'bg', 4.5],
  ['Button text / accent', 'onMint', 'mint', 4.5],
  ['Button text / hover', 'onMint', 'mintStrong', 4.5],
  ['Error text / panel', 'danger', 'surface', 4.5],
  ['Accent 2 (UI) / page', 'accent2', 'bg', 3],
];

// Softer body text (long-form copy): forest keeps its original #c9d6cf, others mix text 70% / muted 30%.
const mix = (a, b, t) => '#' + hex(a).map((v, i) => Math.round(v * t + hex(b)[i] * (1 - t)).toString(16).padStart(2, '0')).join('');
THEMES.forEach((t) => { t.textSoft ??= mix(t.text, t.muted, 0.7); });

const rgb = (h) => hex(h).join(' ');
const css = [
  '/* GENERATED by scripts/themes.mjs — edit that file, then run `npm run themes`. */',
  ...THEMES.map((t) => `:root[data-theme='${t.id}'] {
  --mint: ${t.mint}; --mint-strong: ${t.mintStrong}; --mint-rgb: ${rgb(t.mint)};
  --accent-2: ${t.accent2}; --accent-2-rgb: ${rgb(t.accent2)};
  --bg: ${t.bg}; --bg-rgb: ${rgb(t.bg)}; --surface-rgb: ${rgb(t.surface)};
  --text: ${t.text}; --text-soft: ${t.textSoft}; --muted: ${t.muted}; --danger: ${t.danger}; --on-mint: ${t.onMint};
  --particle: ${t.particle}; --particle-hi: ${t.particleHi}; --particle-blend: ${t.blend};
  color-scheme: ${t.scheme};
}`),
].join('\n');
writeFileSync(new URL('../src/styles/themes.css', import.meta.url), css + '\n');

let fail = 0;
const rows = ['| # | Theme | ' + PAIRS.map((p) => `${p[0]} (≥${p[3]})`).join(' | ') + ' |', '|' + '---|'.repeat(PAIRS.length + 2)];
THEMES.forEach((t, i) => {
  const cells = PAIRS.map(([, f, b, min]) => { const r = ratio(t[f], t[b]); if (r < min) fail++; return `${r.toFixed(2)}${r < min ? ' ❌' : ''}`; });
  rows.push(`| ${i + 1} | ${t.name} \`${t.id}\` | ${cells.join(' | ')} |`);
});
console.log(rows.join('\n'));
console.log(fail ? `\n${fail} pair(s) fail WCAG AA` : '\nAll pairs pass WCAG AA.');
if (fail && process.argv.includes('--check')) process.exit(1);
